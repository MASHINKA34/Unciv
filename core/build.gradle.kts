import com.unciv.build.OnlineSecrets
import org.jetbrains.kotlin.gradle.dsl.JvmTarget

plugins {
    id("kotlin")
}

// Unciv Online: the default server URL and the shared server key are baked into the build as
// com.unciv.online.OnlineBuildConfig, read from the local secrets file (see buildSrc OnlineSecrets).
// The secrets never enter git; without them the build uses placeholders and cannot reach a server.
val onlineSecrets = OnlineSecrets.load(rootDir)
val onlineServerUrl: String = onlineSecrets?.getProperty("server.url")?.trim()?.trimEnd('/')
    ?.takeIf { it.isNotEmpty() } ?: OnlineSecrets.PLACEHOLDER_SERVER_URL
val onlineSharedKey: String = onlineSecrets?.getProperty("shared.key")?.trim() ?: ""
val onlineConfigDir = layout.buildDirectory.dir("generated/onlineBuildConfig")

val generateOnlineBuildConfig by tasks.registering {
    description = "Generates com.unciv.online.OnlineBuildConfig from the local Unciv Online secrets file"
    inputs.property("serverUrl", onlineServerUrl)
    inputs.property("sharedKey", onlineSharedKey)
    outputs.dir(onlineConfigDir)
    val lookup = OnlineSecrets.describeLookup(rootDir)
    doLast {
        fun String.kotlinLiteral() = "\"" + replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$") + "\""
        val file = onlineConfigDir.get().file("com/unciv/online/OnlineBuildConfig.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// Generated by core/build.gradle.kts (generateOnlineBuildConfig) - do not edit, do not commit.
            |package com.unciv.online
            |
            |object OnlineBuildConfig {
            |    /** Default multiplayer server baked into this build */
            |    const val SERVER_URL = ${onlineServerUrl.kotlinLiteral()}
            |    /** Shared key sent to the server in every request; empty when built without secrets */
            |    const val SHARED_KEY = ${onlineSharedKey.kotlinLiteral()}
            |}
            |""".trimMargin(), Charsets.UTF_8
        )
        logger.lifecycle("Unciv Online config: $lookup, server=$onlineServerUrl, sharedKey=${if (onlineSharedKey.isEmpty()) "MISSING" else "set (${onlineSharedKey.length} chars)"}")
    }
}

sourceSets {
    main {
        java.srcDir("src/")
        java.srcDir(generateOnlineBuildConfig)
    }
}


kotlin {
    compilerOptions {
        jvmTarget = JvmTarget.JVM_1_8
        // Fail compilation on JDK APIs missing in Java 8
        freeCompilerArgs.add("-Xjdk-release=8")
    }
}

java {
    sourceCompatibility = JavaVersion.VERSION_1_8
    targetCompatibility = JavaVersion.VERSION_1_8
}

tasks.withType<JavaCompile>().configureEach {
    options.release.set(8)
}
